function stop(files) {
  const dir = sandbox(files);
  execFileSync('git', ['init', '-q', dir]);
  return runHook('stop-checklist', { stop_hook_active: false }, { CLAUDE_PROJECT_DIR: dir }).stdout;
}

test('stop-checklist: only repos with a CHANGELOG.md, only source changes, only once', () => {
  // A brand-new repo: CHANGELOG.md itself is untracked, so it counts as touched. Commit it to see the reminder.
  const dir = sandbox({ 'CHANGELOG.md': '# Changelog\n## Unreleased\n' });
  const sh = (c) => execFileSync('bash', ['-c', c], { cwd: dir });
  sh('git init -q && git -c user.email=t@t -c user.name=t add . && git -c user.email=t@t -c user.name=t -c commit.gpgsign=false commit -qm init');
  sh('mkdir -p src && echo x > src/a.ts');
  const run = (active) => runHook('stop-checklist', { stop_hook_active: active }, { CLAUDE_PROJECT_DIR: dir }).stdout;
  assert.match(run(false), /"decision":\s*"block"/);
  assert.equal(run(true), '');
  sh('echo "- a" >> CHANGELOG.md');
  assert.equal(run(false), '');
  assert.equal(stop({ 'src/a.ts': 'x' }), '');
  assert.equal(stop({ 'CHANGELOG.md': 'x', 'src/a.test.ts': 'x' }), '');
});

