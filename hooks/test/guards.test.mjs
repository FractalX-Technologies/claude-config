// ── wiring ───────────────────────────────────────────────────────────────────────────────────────────
const { hooks } = JSON.parse(readFileSync(path.join(HOOKS_DIR, 'hooks.json'), 'utf8'));

const selects = (group, tool) => new RegExp(`^(${group.matcher ?? '.*'})$`).test(tool);
const scriptOf = (h) => h.command.match(/hooks\/([\w-]+)\.sh$/)[1];

// True when `script` is wired under `event` with a matcher that selects `tool`.
const fires = (event, script, tool) => (hooks[event] ?? []).some((group) =>
  group.hooks.some((h) => h.command.endsWith(`/.claude/hooks/${script}.sh`)) && selects(group, tool));

test('wiring: each guard fires on every tool that can do what it forbids', () => {
  for (const tool of ['Read', 'Grep', 'Bash']) assert.ok(fires('PreToolUse', 'protect-secrets', tool), tool);
  assert.ok(fires('PreToolUse', 'dangerous-commands', 'Bash'));
  for (const script of ['protect-config', 'protect-tests']) {
    for (const tool of ['Edit', 'MultiEdit', 'Write', 'Bash']) assert.ok(fires('PreToolUse', script, tool), `${script} on ${tool}`);
  }
  for (const script of ['guard-generated', 'guard-lockfiles', 'electron-window-baseline', 'short-doc-comments']) {
    for (const tool of ['Edit', 'MultiEdit', 'Write']) assert.ok(fires('PreToolUse', script, tool), `${script} on ${tool}`);
  }
  for (const tool of ['Agent', 'Task']) assert.ok(fires('PreToolUse', 'subagent-cap', tool), tool);
  for (const script of ['dotnet-format-check', 'no-hardcoded-visuals']) assert.ok(fires('PostToolUse', script, 'Edit'), script);
  assert.ok(fires('SessionStart', 'session-context', 'compact'));
  assert.ok(fires('Stop', 'stop-checklist', ''));
});

// The user's call (global CLAUDE.md § Git): no guard stands between Claude and git or gh, on main or anywhere.
test('wiring: git and gh pass every Bash guard, main, rewrites and gh writes included', () => {
  const guards = (hooks.PreToolUse ?? []).filter((g) => selects(g, 'Bash')).flatMap((g) => g.hooks.map(scriptOf));
  for (const command of ['git commit -m x', 'git push origin main', 'git push --force', 'git reset --hard HEAD',
    'git commit --amend', 'git tag v1.0.0', 'gh pr create --fill', 'gh pr merge 12', 'gh api -X POST repos/o/r/issues']) {
    for (const script of guards) {
      const r = runHook(script, { tool_name: 'Bash', permission_mode: 'default', tool_input: { command } });
      assert.equal(r.status, 0, `${script}: ${command}`);
      assert.equal(r.stdout, '', `${script}: ${command}`);
    }
  }
});

test('wiring: every wired script exists, and every script is wired', () => {
  const wired = new Set(Object.values(hooks).flat().flatMap((g) => g.hooks.map(scriptOf)));
  const scripts = execFileSync('bash', ['-c', 'ls *.sh'], { cwd: HOOKS_DIR, encoding: 'utf8' }).trim().split('\n').map((f) => f.replace(/\.sh$/, ''));
  assert.deepEqual([...wired].sort(), scripts.sort());
});
