test('session-context: injects lessons and open decisions, nothing else', () => {
  const dir = sandbox({
    'tasks/lessons.md': '# Lessons\n\n## 2026-09-03 — never cat a dotfile\n- **Pattern:** printed a token.\n- **Rule:** query the SHAPE,\n  never the content.\n\n## 2026-09-23 — url.JoinPath\n- **Rule:** normalise the base URL.\n',
    'tasks/todo.md': '# Task\n## Plan\n- [ ] not a decision\n## Open decisions\n- [ ] **Rotate the PAT**\n- [x] done already\n## Deferred\n- [ ] later\n',
  });
  const ctx = JSON.parse(runHook('session-context', {}, { CLAUDE_PROJECT_DIR: dir }).stdout).hookSpecificOutput.additionalContext;
  assert.match(ctx, /never cat a dotfile: query the SHAPE, never the content\./);
  assert.match(ctx, /url\.JoinPath: normalise the base URL\./);
  assert.match(ctx, /\*\*Rotate the PAT\*\*/);
  assert.doesNotMatch(ctx, /not a decision|done already|later/);
});

