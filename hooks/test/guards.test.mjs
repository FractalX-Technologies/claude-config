test('guard-generated: an existing file with the header is refused; templates and new files pass', () => {
  const header = '// Code generated by tokengen from tokens.json. DO NOT EDIT.\nexport const a = 1;\n';
  const dir = sandbox({ 'src/gen/tokens.ts': header, 'tools/templates/tokens.ts': header, 'src/a.ts': '// mentions Code generated … DO NOT EDIT in passing\nconst a = 1;\n' });
  const write = (rel) => runHook('guard-generated', { tool_name: 'Edit', tool_input: { file_path: path.join(dir, rel) } }, { CLAUDE_PROJECT_DIR: dir });
  const r = write('src/gen/tokens.ts');
  assert.equal(r.status, 2);
  assert.match(r.stderr, /tokengen from tokens\.json/);
  assert.equal(write('tools/templates/tokens.ts').status, 0);
  assert.equal(write('src/new.ts').status, 0);
  assert.equal(write('src/a.ts').status, 0);
});

