// Doc-comment length policy. Pure functions; the hook entry point does the I/O.

// Global CLAUDE.md § Code allows 1–4 lines; the .NET rules allow two at most.
export const maxDocLines = (file) => (file.endsWith('.cs') ? 2 : 4);

const SOURCE = /\.(cs|ts|tsx|mts|cts|js|jsx|mjs|cjs|kt|kts|swift)$/;
const SKIP_PATH = /(^|\/)(node_modules|generated|Generated|vendor|dist|out|build|artifacts|bin|obj)\//;
const GENERATED = /Code generated .* DO NOT EDIT|<auto-generated/;
const DIRECTIVE = /^\/\/\/?\s*(eslint-|@ts-|prettier-ignore|lint:|swiftlint:|MARK:|<reference)/;
const ANNOTATION = /^\s*@[\w.]+(\(.*\))?\s*$/;
const CONTROL = /^(if|for|while|switch|catch|return|else|do|try|function|new|await|throw|typeof|void|delete|yield|super|this)\b/;

// C# is absent on purpose: only a /// run is a doc comment there; a // block above a declaration is
// the reasoning the conventions ask for, not documentation.
const DECLARATION = {
  ts: [
    /^(export\s+)?(default\s+)?(declare\s+)?(abstract\s+)?(async\s+)?(function\b|class\b|interface\b|type\s|enum\s|const\s|let\s|var\s|namespace\s)/,
    /^\s+(public|private|protected|static|readonly|abstract|override|declare|async|get|set|constructor)\b/,
  ],
  kotlin: [/^\s*((public|private|internal|protected|override|open|abstract|sealed|data|enum|inline|value|suspend|operator|infix|tailrec|external|const|lateinit|annotation|companion|expect|actual|inner)\s+)*(fun|class|interface|object|val|var|typealias|constructor|init)\b/],
  swift: [/^\s*((public|private|fileprivate|internal|open|static|class|final|override|mutating|nonmutating|nonisolated|convenience|required|lazy|weak|unowned|dynamic|indirect)\s+)*(func|class|struct|enum|protocol|extension|actor|var|let|init|deinit|subscript|typealias|case)\b/],
};

export function isSourceFile(file) {
  return SOURCE.test(file) && !SKIP_PATH.test(file);
}

export function isGenerated(source) {
  return GENERATED.test(source.split('\n').slice(0, 10).join('\n'));
}

// The XML tags of a C# doc comment are delimiters, like /** and */: they are not prose lines.
const XML_TAG = /<\/?(summary|remarks|para|value|returns|example|inheritdoc)\b[^>]*\/?>/g;

function language(file) {
  if (file.endsWith('.cs')) return 'csharp';
  if (/\.kts?$/.test(file)) return 'kotlin';
  if (file.endsWith('.swift')) return 'swift';
  return 'ts';
}

// A TS method shorthand (`handleKey(input: KeyInput): boolean {`), not a call statement or control flow.
function isTsMethod(line) {
  const t = line.trim();
  return /^\s/.test(line) && !CONTROL.test(t) && !/;\s*$/.test(t) && /^[A-Za-z_$#][\w$]*\??\s*(<[^>]*>)?\s*\(.*\)\s*(:\s*[^=;]+)?\{\s*$/.test(t);
}

function isDeclaration(line, lang) {
  if (DECLARATION[lang].some((re) => re.test(line))) return true;
  return lang === 'ts' && isTsMethod(line);
}

function attached(lines, next, lang) {
  let i = next;
  while (i < lines.length && ANNOTATION.test(lines[i])) i += 1;
  return i < lines.length && isDeclaration(lines[i], lang);
}

function proseLines(body, block) {
  return body
    .filter((l) => !DIRECTIVE.test(l.trim()))
    .map((l) => (block ? l.trim().replace(/^\/\*\*?|\*\/$/g, '').replace(/^\*/, '') : l.trim().replace(/^\/+/, '')).replace(XML_TAG, '').trim())
    .filter((l) => l !== '' && l !== '*/');
}

// Every doc comment in `source`: a /** */ block, a Swift or C# /// run, or a // run attached to a declaration.
export function docComments(source, file) {
  const lang = language(file);
  const lines = source.split('\n');
  const found = [];
  for (let i = 0; i < lines.length; i += 1) {
    const t = lines[i].trim();
    if (t.startsWith('/**')) {
      let end = i;
      while (end < lines.length - 1 && !lines[end].includes('*/')) end += 1;
      const body = lines.slice(i, end + 1);
      found.push({ start: i, text: body.map((l) => l.trim()).join('\n'), prose: proseLines(body, true) });
      i = end;
    } else if (t.startsWith('//')) {
      let end = i;
      while (end + 1 < lines.length && lines[end + 1].trim().startsWith('//')) end += 1;
      const body = lines.slice(i, end + 1);
      const tripleSlash = (lang === 'swift' || lang === 'csharp') && body.every((l) => l.trim().startsWith('///'));
      if (tripleSlash || (lang !== 'csharp' && attached(lines, end + 1, lang))) {
        found.push({ start: i, text: body.map((l) => l.trim()).join('\n'), prose: proseLines(body, false) });
      }
      i = end;
    }
  }
  return found;
}

// Doc comments in `after` that are too long and weren't already in `before` word for word.
export function findLongDocComments(before, after, file) {
  const existing = new Set(docComments(before, file).map((c) => c.text));
  return docComments(after, file)
    .filter((c) => c.prose.length > maxDocLines(file) && !existing.has(c.text))
    .map((c) => ({ line: c.start + 1, lines: c.prose.length, first: c.prose[0] }));
}
